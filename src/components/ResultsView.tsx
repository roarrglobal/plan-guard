import { AnalysisCard } from "./AnalysisCard";
import { FailureModeCard } from "./FailureModeCard";
import { Button } from "@/components/ui/button";
import { Copy, Plus, Save, Check } from "lucide-react";
import { useState } from "react";
import { useToast } from "@/hooks/use-toast";

export interface AnalysisResult {
  blind_spots: string[];
  failure_modes: {
    what: string;
    mechanism: string;
    likelihood: "High" | "Medium" | "Low";
    impact: string;
  }[];
  warning_signals: string[];
  kill_criteria: string[];
  unasked_question: string;
}

interface ResultsViewProps {
  result: AnalysisResult;
  originalInput: string;
  onNewAnalysis: () => void;
  onSave?: () => void;
  isLoggedIn?: boolean;
}

export function ResultsView({
  result,
  originalInput,
  onNewAnalysis,
  onSave,
  isLoggedIn = false,
}: ResultsViewProps) {
  const [copied, setCopied] = useState(false);
  const { toast } = useToast();

  const formatForCopy = () => {
    let text = `PRE-MORTEM ANALYSIS\n\n`;
    text += `Plan: ${originalInput}\n\n`;
    text += `---\n\n`;

    text += `BLIND SPOTS\n`;
    result.blind_spots.forEach((spot, i) => {
      text += `• ${spot}\n`;
    });
    text += `\n`;

    text += `FAILURE MODES\n`;
    result.failure_modes.forEach((mode, i) => {
      text += `${i + 1}. ${mode.what}\n`;
      text += `   Mechanism: ${mode.mechanism}\n`;
      text += `   Likelihood: ${mode.likelihood}\n`;
      text += `   Impact: ${mode.impact}\n\n`;
    });

    text += `EARLY WARNING SIGNALS\n`;
    result.warning_signals.forEach((signal) => {
      text += `• ${signal}\n`;
    });
    text += `\n`;

    text += `KILL CRITERIA\n`;
    result.kill_criteria.forEach((criteria) => {
      text += `• ${criteria}\n`;
    });
    text += `\n`;

    text += `THE UNASKED QUESTION\n`;
    text += `"${result.unasked_question}"\n\n`;

    text += `---\nGenerated by Snag`;

    return text;
  };

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(formatForCopy());
      setCopied(true);
      toast({
        title: "Copied to clipboard",
        description: "Analysis copied in plain text format",
      });
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast({
        title: "Failed to copy",
        description: "Please try again",
        variant: "destructive",
      });
    }
  };

  return (
    <div className="flex flex-col min-h-screen">
      {/* Results content */}
      <div className="flex-1 p-4 pb-32 space-y-4 animate-fade-in-up">
        {/* Blind Spots */}
        <AnalysisCard title="Blind Spots" icon="blindspots" className="animate-delay-100">
          <ul className="space-y-2">
            {result.blind_spots.map((spot, i) => (
              <li key={i} className="flex items-start gap-2 text-secondary-foreground">
                <span className="w-1.5 h-1.5 rounded-full bg-warning mt-2 flex-shrink-0" />
                <span>{spot}</span>
              </li>
            ))}
          </ul>
        </AnalysisCard>

        {/* Failure Modes */}
        <AnalysisCard title="Failure Modes" icon="failures" className="animate-delay-200">
          <div className="space-y-3">
            {result.failure_modes.map((mode, i) => (
              <FailureModeCard key={i} mode={mode} index={i + 1} />
            ))}
          </div>
        </AnalysisCard>

        {/* Warning Signals */}
        <AnalysisCard title="Early Warning Signals" icon="warnings" className="animate-delay-300">
          <ul className="space-y-2">
            {result.warning_signals.map((signal, i) => (
              <li key={i} className="flex items-start gap-2 text-secondary-foreground">
                <span className="w-1.5 h-1.5 rounded-full bg-primary mt-2 flex-shrink-0" />
                <span>{signal}</span>
              </li>
            ))}
          </ul>
        </AnalysisCard>

        {/* Kill Criteria */}
        <AnalysisCard title="Kill Criteria" icon="kill" className="animate-delay-400">
          <ul className="space-y-3">
            {result.kill_criteria.map((criteria, i) => (
              <li
                key={i}
                className="text-secondary-foreground bg-destructive/5 border border-destructive/20 rounded-lg p-3 text-sm"
              >
                {criteria}
              </li>
            ))}
          </ul>
        </AnalysisCard>

        {/* The Unasked Question */}
        <AnalysisCard
          title="The Unasked Question"
          icon="question"
          highlight
          className="animate-delay-500"
        >
          <blockquote className="text-lg font-medium text-foreground italic border-l-4 border-accent pl-4 py-2">
            "{result.unasked_question}"
          </blockquote>
        </AnalysisCard>
      </div>

      {/* Fixed bottom actions */}
      <div className="fixed bottom-0 left-0 right-0 bg-background/95 backdrop-blur-lg border-t border-border p-4 safe-bottom">
        <div className="flex gap-3 max-w-lg mx-auto">
          <Button
            variant="secondary"
            onClick={handleCopy}
            className="flex-1"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4" />
                Copied
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                Copy
              </>
            )}
          </Button>

          {onSave && (
            <Button
              variant="secondary"
              onClick={onSave}
              className="flex-1"
            >
              <Save className="w-4 h-4" />
              {isLoggedIn ? "Save" : "Save (Login)"}
            </Button>
          )}

          <Button
            variant="hero"
            onClick={onNewAnalysis}
            className="flex-1"
          >
            <Plus className="w-4 h-4" />
            New
          </Button>
        </div>
      </div>
    </div>
  );
}
