import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { format } from "date-fns";

// McKinsey-style color palette
const COLORS = {
  primary: [0, 71, 171] as [number, number, number], // Cobalt blue
  secondary: [51, 51, 51] as [number, number, number], // Dark gray
  accent: [217, 119, 6] as [number, number, number], // Amber
  success: [16, 185, 129] as [number, number, number], // Emerald
  danger: [220, 38, 38] as [number, number, number], // Red
  muted: [128, 128, 128] as [number, number, number],
  lightGray: [245, 245, 245] as [number, number, number],
  white: [255, 255, 255] as [number, number, number],
};

interface PDFOptions {
  title: string;
  subtitle?: string;
  date?: Date;
  author?: string;
}

// Initialize PDF with consistent styling
function createPDF(options: PDFOptions): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;

  // Header bar
  doc.setFillColor(...COLORS.primary);
  doc.rect(0, 0, pageWidth, 35, "F");

  // Title
  doc.setTextColor(...COLORS.white);
  doc.setFontSize(22);
  doc.setFont("helvetica", "bold");
  doc.text(options.title.toUpperCase(), margin, 18);

  // Subtitle
  if (options.subtitle) {
    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");
    doc.text(options.subtitle, margin, 26);
  }

  // Date and Author
  doc.setFontSize(9);
  const dateStr = format(options.date || new Date(), "MMMM d, yyyy");
  doc.text(dateStr, pageWidth - margin, 18, { align: "right" });
  
  if (options.author) {
    doc.text(`Prepared for: ${options.author}`, pageWidth - margin, 26, { align: "right" });
  }

  // Footer
  const addFooter = (pageNum: number) => {
    doc.setFillColor(...COLORS.lightGray);
    doc.rect(0, pageHeight - 15, pageWidth, 15, "F");
    doc.setTextColor(...COLORS.muted);
    doc.setFontSize(8);
    doc.text(`Generated by Snag | Confidential`, margin, pageHeight - 6);
    doc.text(`Page ${pageNum}`, pageWidth - margin, pageHeight - 6, { align: "right" });
  };

  addFooter(1);

  // Reset for content
  doc.setTextColor(...COLORS.secondary);

  return doc;
}

// Add section header with accent line
function addSectionHeader(doc: jsPDF, title: string, yPos: number, color: [number, number, number] = COLORS.primary): number {
  const margin = 20;
  
  // Section line
  doc.setDrawColor(...color);
  doc.setLineWidth(1);
  doc.line(margin, yPos, margin + 30, yPos);
  
  // Section title
  doc.setTextColor(...color);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text(title.toUpperCase(), margin, yPos + 8);
  
  doc.setTextColor(...COLORS.secondary);
  doc.setFont("helvetica", "normal");
  
  return yPos + 15;
}

// Add bullet point list
function addBulletList(doc: jsPDF, items: string[], yPos: number, bulletColor: [number, number, number] = COLORS.primary): number {
  const margin = 20;
  const maxWidth = doc.internal.pageSize.getWidth() - margin * 2 - 10;
  let currentY = yPos;

  doc.setFontSize(10);

  items.forEach((item) => {
    // Check for page break
    if (currentY > 260) {
      doc.addPage();
      currentY = 30;
    }

    // Bullet
    doc.setFillColor(...bulletColor);
    doc.circle(margin + 2, currentY - 1.5, 1.2, "F");

    // Text
    doc.setTextColor(...COLORS.secondary);
    const lines = doc.splitTextToSize(item, maxWidth);
    doc.text(lines, margin + 8, currentY);
    currentY += lines.length * 5 + 3;
  });

  return currentY + 5;
}

// Add numbered list
function addNumberedList(doc: jsPDF, items: { title: string; details?: string[] }[], yPos: number): number {
  const margin = 20;
  const maxWidth = doc.internal.pageSize.getWidth() - margin * 2 - 15;
  let currentY = yPos;

  items.forEach((item, index) => {
    // Check for page break
    if (currentY > 250) {
      doc.addPage();
      currentY = 30;
    }

    // Number circle
    doc.setFillColor(...COLORS.primary);
    doc.circle(margin + 4, currentY - 1.5, 4, "F");
    doc.setTextColor(...COLORS.white);
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.text(String(index + 1), margin + 4, currentY, { align: "center" });

    // Title
    doc.setTextColor(...COLORS.secondary);
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    const titleLines = doc.splitTextToSize(item.title, maxWidth);
    doc.text(titleLines, margin + 12, currentY);
    currentY += titleLines.length * 5 + 2;

    // Details
    if (item.details && item.details.length > 0) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9);
      doc.setTextColor(...COLORS.muted);
      item.details.forEach((detail) => {
        const detailLines = doc.splitTextToSize(`• ${detail}`, maxWidth - 5);
        doc.text(detailLines, margin + 15, currentY);
        currentY += detailLines.length * 4 + 1;
      });
    }

    currentY += 5;
  });

  return currentY + 5;
}

// Add highlight box
function addHighlightBox(doc: jsPDF, title: string, content: string, yPos: number, color: [number, number, number] = COLORS.primary): number {
  const margin = 20;
  const boxWidth = doc.internal.pageSize.getWidth() - margin * 2;
  
  // Calculate height needed
  doc.setFontSize(10);
  const contentLines = doc.splitTextToSize(content, boxWidth - 20);
  const boxHeight = 15 + contentLines.length * 5;

  // Check for page break
  if (yPos + boxHeight > 260) {
    doc.addPage();
    yPos = 30;
  }

  // Box background with opacity simulation
  const bgColor = color.map(c => Math.round(c + (255 - c) * 0.9)) as [number, number, number];
  doc.setFillColor(...bgColor);
  doc.roundedRect(margin, yPos, boxWidth, boxHeight, 3, 3, "F");

  // Left accent bar
  doc.setFillColor(...color);
  doc.rect(margin, yPos, 3, boxHeight, "F");

  // Title
  doc.setTextColor(...color);
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text(title, margin + 10, yPos + 8);

  // Content
  doc.setTextColor(...COLORS.secondary);
  doc.setFont("helvetica", "italic");
  doc.text(contentLines, margin + 10, yPos + 16);

  return yPos + boxHeight + 10;
}

// ============ PRE-MORTEM EXPORT ============
export interface PreMortemData {
  originalInput: string;
  blindSpots: Array<{ blind_spot: string; why_it_matters?: string; how_to_test?: string } | string>;
  failureModes: Array<{
    what_fails?: string;
    what?: string;
    mechanism: string;
    likelihood: string;
    impact?: string;
    mitigation?: string;
  }>;
  warningSignals: Array<{ signal: string; timeframe?: string } | string>;
  killCriteria: Array<{ condition: string; action: string; threshold?: string } | string>;
  unaskedQuestion: string;
  category?: string;
}

export function exportPreMortemPDF(data: PreMortemData, author?: string): void {
  const doc = createPDF({
    title: "Pre-Mortem Analysis",
    subtitle: data.category ? `Category: ${data.category}` : undefined,
    author,
  });

  let yPos = 50;
  const margin = 20;

  // Executive Summary
  yPos = addSectionHeader(doc, "Executive Summary", yPos);
  doc.setFontSize(10);
  const summaryLines = doc.splitTextToSize(data.originalInput, doc.internal.pageSize.getWidth() - margin * 2);
  doc.text(summaryLines, margin, yPos);
  yPos += summaryLines.length * 5 + 15;

  // Blind Spots
  yPos = addSectionHeader(doc, "Blind Spots Identified", yPos, COLORS.primary);
  const blindSpotItems = data.blindSpots.map((spot) => {
    if (typeof spot === "string") return spot;
    return `${spot.blind_spot}${spot.why_it_matters ? ` — ${spot.why_it_matters}` : ""}`;
  });
  yPos = addBulletList(doc, blindSpotItems, yPos, COLORS.primary);

  // Failure Modes
  yPos = addSectionHeader(doc, "Failure Modes", yPos, COLORS.danger);
  const failureModeItems = data.failureModes.map((mode) => ({
    title: mode.what_fails || mode.what || "Unknown",
    details: [
      `Mechanism: ${mode.mechanism}`,
      `Likelihood: ${mode.likelihood}`,
      mode.impact ? `Impact: ${mode.impact}` : "",
      mode.mitigation ? `Mitigation: ${mode.mitigation}` : "",
    ].filter(Boolean),
  }));
  yPos = addNumberedList(doc, failureModeItems, yPos);

  // Warning Signals
  yPos = addSectionHeader(doc, "Warning Signals", yPos, COLORS.accent);
  const warningItems = data.warningSignals.map((signal) => {
    if (typeof signal === "string") return signal;
    return `${signal.signal}${signal.timeframe ? ` [${signal.timeframe}]` : ""}`;
  });
  yPos = addBulletList(doc, warningItems, yPos, COLORS.accent);

  // Kill Criteria
  yPos = addSectionHeader(doc, "Kill Criteria", yPos, COLORS.muted);
  const killItems = data.killCriteria.map((criteria) => {
    if (typeof criteria === "string") return criteria;
    return `${criteria.condition} → ${criteria.action}${criteria.threshold ? ` (Threshold: ${criteria.threshold})` : ""}`;
  });
  yPos = addBulletList(doc, killItems, yPos, COLORS.muted);

  // The Unasked Question
  yPos = addHighlightBox(doc, "THE UNASKED QUESTION", `"${data.unaskedQuestion}"`, yPos, COLORS.primary);

  // Save
  doc.save(`PreMortem_Analysis_${format(new Date(), "yyyy-MM-dd")}.pdf`);
}

// ============ POST-MORTEM EXPORT ============
export interface PostMortemData {
  title: string;
  description: string;
  postMortemType: string;
  outcomeStatus?: string;
  outcomeRating?: number;
  analysis?: {
    summary?: string;
    root_causes?: string[];
    what_worked?: string[];
    what_didnt?: string[];
    lessons?: string[];
    action_items?: string[];
    uncomfortable_truth?: string;
    one_line_wisdom?: string;
  };
}

export function exportPostMortemPDF(data: PostMortemData, author?: string): void {
  const doc = createPDF({
    title: "Post-Mortem Analysis",
    subtitle: `Type: ${data.postMortemType}${data.outcomeStatus ? ` | Outcome: ${data.outcomeStatus}` : ""}`,
    author,
  });

  let yPos = 50;
  const margin = 20;

  // Situation Overview
  yPos = addSectionHeader(doc, "Situation Overview", yPos);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text(data.title || "Post-Mortem Analysis", margin, yPos);
  yPos += 8;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  const descLines = doc.splitTextToSize(data.description, doc.internal.pageSize.getWidth() - margin * 2);
  doc.text(descLines, margin, yPos);
  yPos += descLines.length * 5 + 15;

  if (data.analysis) {
    // Summary
    if (data.analysis.summary) {
      yPos = addHighlightBox(doc, "EXECUTIVE SUMMARY", data.analysis.summary, yPos, COLORS.primary);
    }

    // Root Causes
    if (data.analysis.root_causes?.length) {
      yPos = addSectionHeader(doc, "Root Causes", yPos, COLORS.danger);
      yPos = addBulletList(doc, data.analysis.root_causes, yPos, COLORS.danger);
    }

    // What Worked
    if (data.analysis.what_worked?.length) {
      yPos = addSectionHeader(doc, "What Worked", yPos, COLORS.success);
      yPos = addBulletList(doc, data.analysis.what_worked, yPos, COLORS.success);
    }

    // What Didn't Work
    if (data.analysis.what_didnt?.length) {
      yPos = addSectionHeader(doc, "What Didn't Work", yPos, COLORS.accent);
      yPos = addBulletList(doc, data.analysis.what_didnt, yPos, COLORS.accent);
    }

    // Lessons Learned
    if (data.analysis.lessons?.length) {
      yPos = addSectionHeader(doc, "Lessons Learned", yPos, COLORS.primary);
      const lessonItems = data.analysis.lessons.map((lesson, i) => ({
        title: lesson,
      }));
      yPos = addNumberedList(doc, lessonItems, yPos);
    }

    // Action Items
    if (data.analysis.action_items?.length) {
      yPos = addSectionHeader(doc, "Action Items", yPos, COLORS.primary);
      
      // Create a table for action items
      autoTable(doc, {
        startY: yPos,
        head: [["#", "Action Item", "Status"]],
        body: data.analysis.action_items.map((item, i) => [
          String(i + 1),
          item,
          "☐ Pending",
        ]),
        theme: "striped",
        headStyles: {
          fillColor: COLORS.primary,
          fontSize: 9,
        },
        bodyStyles: {
          fontSize: 9,
        },
        margin: { left: margin, right: margin },
      });
      
      yPos = (doc as any).lastAutoTable.finalY + 15;
    }

    // Uncomfortable Truth
    if (data.analysis.uncomfortable_truth) {
      yPos = addHighlightBox(doc, "THE UNCOMFORTABLE TRUTH", `"${data.analysis.uncomfortable_truth}"`, yPos, COLORS.danger);
    }

    // One Line Wisdom
    if (data.analysis.one_line_wisdom) {
      yPos = addHighlightBox(doc, "KEY TAKEAWAY", `"${data.analysis.one_line_wisdom}"`, yPos, COLORS.primary);
    }
  }

  // Save
  doc.save(`PostMortem_Analysis_${format(new Date(), "yyyy-MM-dd")}.pdf`);
}

// ============ FRAMEWORK EXPORT ============
export interface FrameworkData {
  title: string;
  frameworkType: "swot" | "porter" | "premortem";
  inputs: Record<string, unknown>;
  aiEnhancement?: Record<string, unknown>;
}

export function exportFrameworkPDF(data: FrameworkData, author?: string): void {
  const frameworkNames: Record<string, string> = {
    swot: "SWOT Analysis",
    porter: "Porter's Five Forces",
    premortem: "Pre-Mortem Framework",
  };

  const doc = createPDF({
    title: frameworkNames[data.frameworkType] || "Strategic Framework",
    subtitle: data.title,
    author,
  });

  let yPos = 50;
  const margin = 20;
  const pageWidth = doc.internal.pageSize.getWidth();

  if (data.frameworkType === "swot") {
    // SWOT 2x2 Grid
    const boxWidth = (pageWidth - margin * 2 - 10) / 2;
    const boxHeight = 80;

    const swotData = data.inputs as {
      strengths?: string[];
      weaknesses?: string[];
      opportunities?: string[];
      threats?: string[];
    };

    const quadrants = [
      { title: "STRENGTHS", items: swotData.strengths || [], color: COLORS.success, x: margin, y: yPos },
      { title: "WEAKNESSES", items: swotData.weaknesses || [], color: COLORS.danger, x: margin + boxWidth + 10, y: yPos },
      { title: "OPPORTUNITIES", items: swotData.opportunities || [], color: COLORS.primary, x: margin, y: yPos + boxHeight + 10 },
      { title: "THREATS", items: swotData.threats || [], color: COLORS.accent, x: margin + boxWidth + 10, y: yPos + boxHeight + 10 },
    ];

    quadrants.forEach((q) => {
      // Box background with opacity simulation
      const bgColor = q.color.map(c => Math.round(c + (255 - c) * 0.9)) as [number, number, number];
      doc.setFillColor(...bgColor);
      doc.roundedRect(q.x, q.y, boxWidth, boxHeight, 3, 3, "F");

      // Title
      doc.setFillColor(...q.color);
      doc.roundedRect(q.x, q.y, boxWidth, 12, 3, 3, "F");
      doc.setTextColor(...COLORS.white);
      doc.setFontSize(10);
      doc.setFont("helvetica", "bold");
      doc.text(q.title, q.x + boxWidth / 2, q.y + 8, { align: "center" });

      // Items
      doc.setTextColor(...COLORS.secondary);
      doc.setFontSize(8);
      doc.setFont("helvetica", "normal");
      q.items.slice(0, 5).forEach((item, i) => {
        const truncated = item.length > 40 ? item.substring(0, 37) + "..." : item;
        doc.text(`• ${truncated}`, q.x + 5, q.y + 20 + i * 10);
      });
    });

    yPos += boxHeight * 2 + 30;
  } else if (data.frameworkType === "porter") {
    // Porter's Five Forces
    const porterData = data.inputs as {
      rivalry?: { rating: number; notes: string };
      newEntrants?: { rating: number; notes: string };
      substitutes?: { rating: number; notes: string };
      buyerPower?: { rating: number; notes: string };
      supplierPower?: { rating: number; notes: string };
    };

    const forces = [
      { key: "rivalry", label: "Competitive Rivalry", color: COLORS.danger },
      { key: "newEntrants", label: "Threat of New Entrants", color: [128, 0, 128] as [number, number, number] },
      { key: "substitutes", label: "Threat of Substitutes", color: COLORS.accent },
      { key: "buyerPower", label: "Buyer Power", color: COLORS.primary },
      { key: "supplierPower", label: "Supplier Power", color: COLORS.success },
    ];

    yPos = addSectionHeader(doc, "Competitive Forces Analysis", yPos);

    // Create table data
    const tableData = forces.map((force) => {
      const forceData = porterData[force.key as keyof typeof porterData];
      const rating = forceData?.rating || 0;
      const intensity = rating > 66 ? "High" : rating > 33 ? "Medium" : "Low";
      return [force.label, `${rating}%`, intensity, forceData?.notes || "-"];
    });

    autoTable(doc, {
      startY: yPos,
      head: [["Force", "Rating", "Intensity", "Notes"]],
      body: tableData,
      theme: "striped",
      headStyles: {
        fillColor: COLORS.primary,
        fontSize: 9,
      },
      bodyStyles: {
        fontSize: 8,
      },
      columnStyles: {
        0: { cellWidth: 45 },
        1: { cellWidth: 20, halign: "center" },
        2: { cellWidth: 25, halign: "center" },
        3: { cellWidth: "auto" },
      },
      margin: { left: margin, right: margin },
    });

    yPos = (doc as any).lastAutoTable.finalY + 15;

    // Visual gauge for each force
    yPos = addSectionHeader(doc, "Force Intensity Visualization", yPos);
    
    forces.forEach((force, index) => {
      const forceData = porterData[force.key as keyof typeof porterData];
      const rating = forceData?.rating || 0;
      
      if (yPos > 250) {
        doc.addPage();
        yPos = 30;
      }

      doc.setFontSize(9);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(...COLORS.secondary);
      doc.text(force.label, margin, yPos);
      
      // Draw gauge background
      const gaugeWidth = 100;
      const gaugeHeight = 6;
      const gaugeX = margin + 55;
      
      doc.setFillColor(...COLORS.lightGray);
      doc.roundedRect(gaugeX, yPos - 4, gaugeWidth, gaugeHeight, 2, 2, "F");
      
      // Draw gauge fill
      doc.setFillColor(...force.color);
      doc.roundedRect(gaugeX, yPos - 4, (rating / 100) * gaugeWidth, gaugeHeight, 2, 2, "F");
      
      // Draw rating text
      doc.setFontSize(8);
      doc.setFont("helvetica", "normal");
      doc.text(`${rating}%`, gaugeX + gaugeWidth + 5, yPos);
      
      yPos += 12;
    });

    yPos += 10;
  }

  // AI Enhancement if available
  if (data.aiEnhancement) {
    yPos = addSectionHeader(doc, "AI Strategic Insights", yPos, COLORS.primary);
    
    Object.entries(data.aiEnhancement).forEach(([key, value]) => {
      if (Array.isArray(value) && value.length > 0) {
        doc.setFontSize(10);
        doc.setFont("helvetica", "bold");
        doc.text(key.replace(/_/g, " ").toUpperCase(), margin, yPos);
        yPos += 6;
        yPos = addBulletList(doc, value as string[], yPos, COLORS.primary);
      }
    });
  }

  // Save
  doc.save(`${data.frameworkType.toUpperCase()}_Analysis_${format(new Date(), "yyyy-MM-dd")}.pdf`);
}

// ============ DECISION EXPORT ============
export interface DecisionData {
  decisionText: string;
  options?: Array<{ text: string }>;
  stakes?: string;
  category?: string;
  chosenOption?: string;
  confidence?: number;
  aiNudge?: string;
  outcomeStatus?: string;
  outcomeNotes?: string;
}

export function exportDecisionPDF(data: DecisionData, author?: string): void {
  const doc = createPDF({
    title: "Decision Analysis",
    subtitle: data.category ? `Category: ${data.category}` : undefined,
    author,
  });

  let yPos = 50;
  const margin = 20;

  // Decision Statement
  yPos = addSectionHeader(doc, "Decision Statement", yPos);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  const decisionLines = doc.splitTextToSize(data.decisionText, doc.internal.pageSize.getWidth() - margin * 2);
  doc.text(decisionLines, margin, yPos);
  yPos += decisionLines.length * 6 + 10;

  // Stakes
  if (data.stakes) {
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    const stakesColor = data.stakes === "high" ? COLORS.danger : data.stakes === "medium" ? COLORS.accent : COLORS.success;
    doc.setTextColor(...stakesColor);
    doc.text(`Stakes: ${data.stakes.toUpperCase()}`, margin, yPos);
    yPos += 10;
  }

  // Options
  if (data.options?.length) {
    yPos = addSectionHeader(doc, "Options Considered", yPos);
    const optionItems = data.options.map((opt, i) => ({
      title: opt.text,
      details: data.chosenOption === opt.text ? ["✓ CHOSEN OPTION"] : [],
    }));
    yPos = addNumberedList(doc, optionItems, yPos);
  }

  // AI Insight
  if (data.aiNudge) {
    yPos = addHighlightBox(doc, "AI REFLECTION", data.aiNudge, yPos, COLORS.primary);
  }

  // Outcome (if available)
  if (data.outcomeStatus) {
    yPos = addSectionHeader(doc, "Outcome", yPos, data.outcomeStatus === "success" ? COLORS.success : COLORS.accent);
    doc.setFontSize(10);
    doc.text(`Status: ${data.outcomeStatus}`, margin, yPos);
    yPos += 8;
    
    if (data.outcomeNotes) {
      const notesLines = doc.splitTextToSize(data.outcomeNotes, doc.internal.pageSize.getWidth() - margin * 2);
      doc.text(notesLines, margin, yPos);
    }
  }

  // Save
  doc.save(`Decision_Analysis_${format(new Date(), "yyyy-MM-dd")}.pdf`);
}
