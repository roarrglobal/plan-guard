import { ArrowLeft, Copy, Plus, Check } from "lucide-react";
import { useState } from "react";
import { useToast } from "@/hooks/use-toast";
import { AnalysisSection } from "./AnalysisSection";
import { FailureModeItem } from "./FailureModeItem";

export interface AnalysisResult {
  blind_spots: string[];
  failure_modes: {
    what: string;
    mechanism: string;
    likelihood: "High" | "Medium" | "Low";
    impact: string;
  }[];
  warning_signals: string[];
  kill_criteria: string[];
  unasked_question: string;
}

interface AnalysisResultsProps {
  result: AnalysisResult;
  originalInput: string;
  onNewAnalysis: () => void;
  onSave?: () => void;
  isLoggedIn?: boolean;
}

export function AnalysisResults({
  result,
  originalInput,
  onNewAnalysis,
  onSave,
  isLoggedIn = false,
}: AnalysisResultsProps) {
  const [copied, setCopied] = useState(false);
  const { toast } = useToast();

  const formatForCopy = () => {
    let text = `PRE-MORTEM ANALYSIS\n\n`;
    text += `Plan: ${originalInput}\n\n`;
    text += `---\n\n`;

    text += `BLIND SPOTS\n`;
    result.blind_spots.forEach((spot) => {
      text += `• ${spot}\n`;
    });
    text += `\n`;

    text += `FAILURE MODES\n`;
    result.failure_modes.forEach((mode, i) => {
      text += `${i + 1}. ${mode.what}\n`;
      text += `   Mechanism: ${mode.mechanism}\n`;
      text += `   Likelihood: ${mode.likelihood}\n`;
      text += `   Impact: ${mode.impact}\n\n`;
    });

    text += `EARLY WARNING SIGNALS\n`;
    result.warning_signals.forEach((signal) => {
      text += `• ${signal}\n`;
    });
    text += `\n`;

    text += `KILL CRITERIA\n`;
    result.kill_criteria.forEach((criteria) => {
      text += `• ${criteria}\n`;
    });
    text += `\n`;

    text += `THE UNASKED QUESTION\n`;
    text += `"${result.unasked_question}"\n\n`;

    text += `---\nGenerated by Snag`;

    return text;
  };

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(formatForCopy());
      setCopied(true);
      toast({
        title: "Copied to clipboard",
        description: "Analysis copied in plain text format",
      });
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast({
        title: "Failed to copy",
        description: "Please try again",
        variant: "destructive",
      });
    }
  };

  return (
    <div className="min-h-screen bg-[#FAFAFA] flex flex-col">
      {/* Header */}
      <header className="sticky top-0 z-40 bg-white border-b border-[#E5E5E5]">
        <div className="flex items-center justify-between px-4 py-3">
          <button
            onClick={onNewAnalysis}
            className="p-2 -ml-2 text-[#666666] hover:text-[#1A1A1A] transition-colors"
            aria-label="Back"
          >
            <ArrowLeft className="w-5 h-5" />
          </button>
          <span className="text-[18px] font-bold text-[#1A1A1A]">
            SNAG ANALYSIS
          </span>
          <div className="w-9" />
        </div>
      </header>

      {/* Content */}
      <main className="flex-1 px-4 py-4 pb-24 max-w-[680px] mx-auto w-full">
        {/* Plan Summary Card */}
        <div className="bg-white border border-[#E5E5E5] rounded-lg p-4 mb-4">
          <p className="text-[11px] font-semibold text-[#999999] uppercase tracking-wide mb-2">
            YOUR PLAN
          </p>
          <p className="text-[15px] text-[#333333] leading-relaxed">
            {originalInput}
          </p>
        </div>

        {/* Analysis Sections */}
        <AnalysisSection title="Blind Spots" accentColor="cobalt">
          <ul className="space-y-2">
            {result.blind_spots.map((spot, i) => (
              <li
                key={i}
                className="flex items-start gap-3 text-[15px] text-[#333333] leading-relaxed"
              >
                <span className="w-1.5 h-1.5 rounded-full bg-[#999999] mt-2 flex-shrink-0" />
                <span>{spot}</span>
              </li>
            ))}
          </ul>
        </AnalysisSection>

        <AnalysisSection title="Failure Modes" accentColor="red">
          <div>
            {result.failure_modes.map((mode, i) => (
              <FailureModeItem key={i} mode={mode} index={i + 1} />
            ))}
          </div>
        </AnalysisSection>

        <AnalysisSection title="Warning Signals" accentColor="amber">
          <ul className="space-y-2">
            {result.warning_signals.map((signal, i) => (
              <li
                key={i}
                className="flex items-start gap-3 text-[15px] text-[#333333] leading-relaxed"
              >
                <span className="w-1.5 h-1.5 rounded-full bg-[#999999] mt-2 flex-shrink-0" />
                <span>{signal}</span>
              </li>
            ))}
          </ul>
        </AnalysisSection>

        <AnalysisSection title="Kill Criteria" accentColor="gray">
          <ol className="space-y-2">
            {result.kill_criteria.map((criteria, i) => (
              <li
                key={i}
                className="flex items-start gap-3 text-[15px] text-[#333333] leading-relaxed"
              >
                <span className="text-[15px] font-medium text-[#666666] flex-shrink-0">
                  {i + 1}.
                </span>
                <span>{criteria}</span>
              </li>
            ))}
          </ol>
        </AnalysisSection>

        <AnalysisSection title="The Unasked Question" accentColor="cobalt">
          <p className="text-[16px] font-medium text-[#1A1A1A] italic leading-relaxed">
            "{result.unasked_question}"
          </p>
        </AnalysisSection>
      </main>

      {/* Fixed Bottom Actions */}
      <div className="fixed bottom-0 left-0 right-0 bg-white border-t border-[#E5E5E5] px-4 py-3 safe-bottom">
        <div className="flex gap-3 max-w-[680px] mx-auto">
          <button
            onClick={handleCopy}
            className="flex-1 flex items-center justify-center gap-2 bg-[#F2F2F2] text-[#333333] border border-[#E0E0E0] rounded-lg py-3 min-h-[48px] text-[14px] font-medium transition-colors hover:bg-[#E8E8E8]"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4" />
                Copied
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                Copy Analysis
              </>
            )}
          </button>

          <button
            onClick={onNewAnalysis}
            className="flex-1 flex items-center justify-center gap-2 bg-[#0047AB] text-white rounded-lg py-3 min-h-[48px] text-[14px] font-medium transition-colors hover:bg-[#003A8C]"
          >
            <Plus className="w-4 h-4" />
            New Analysis
          </button>
        </div>

        {onSave && !isLoggedIn && (
          <button
            onClick={onSave}
            className="w-full text-center text-[14px] font-medium text-[#0047AB] mt-2 py-2"
          >
            Save this analysis
          </button>
        )}
      </div>
    </div>
  );
}
